        private const string Initials = "ABDEFGIKLMNOPRSTVY";

        internal static Department For(ThemeChoice id) =>
            Departments.TryGetValue(id, out Department department) ? department : Departments[ThemeChoice.Corporate];

        /// <summary>The department's memos: the theme's own and the ones here.</summary>
        internal static List<string> MemosFor(Theme theme) => Join(theme.Memos, For(theme.Id).Memos);

        internal static List<string> HeadlinesFor(Theme theme)
        {
            List<string> all = Join(theme.Headlines, For(theme.Id).Headlines);
            all.AddRange(CommonHeadlines);
            return all;
        }

        internal static List<string> ChatterFor(Theme theme) => Join(theme.Chatter, For(theme.Id).Chatter);

        /// <summary>A signature line for a memo: a person, their title, a reference.</summary>
        internal static string Signature(System.Random random, ThemeChoice id, string sender = null)
        {
            Department department = For(id);
            string name = Initials[random.Next(Initials.Length)] + ". " + Surnames[random.Next(Surnames.Length)];
            string title = sender ?? department.Titles[random.Next(department.Titles.Length)];
            string code = sender != null ? CodeFor(sender) : department.Code;
            return $"SIGNED: {name}, {title}  //  REF {code}-{random.Next(100, 10000):0000}";
        }

        private static string CodeFor(string sender)
        {
            switch (sender)
            {
                case "HUMAN RESOURCES": return "HR";
                case "FACILITIES": return "FAC";
                case "IT DEPARTMENT": return "IT";
                case "COMPLIANCE": return "CMP";
                case "OFFICE OF THE CEO": return "HQ";
                case "SECURITY": return "SEC";
                case "LEGAL": return "LGL";
                case "FINANCE": return "FIN";
                default: return "TG";
            }
        }

        private static List<string> Join(string[] a, string[] b)
        {
            var all = new List<string>();
            if (a != null)
            {
                all.AddRange(a);
            }
            if (b != null)
            {
                all.AddRange(b);
            }
            return all;
        }
